// Regenerates apps/docs/src/pages/studio/system-source-files.ts: the code view of each system example.
import { relative, resolve } from 'node:path'

const root = resolve(import.meta.dirname!, '..'), src = resolve(root, 'examples/systems/src')
const files: string[] = []
const walk = (dir: string) => {
  for (const entry of Deno.readDirSync(dir)) {
    const path = resolve(dir, entry.name)
    if (entry.isDirectory) walk(path)
    else if (/\.tsx?$/.test(entry.name) && entry.name !== 'index.ts') files.push(relative(src, path))
  }
}
walk(src)
files.sort()
const name = (index: number) => `s${index}`
const groups = new Map<string, string[]>()
files.forEach((file) => {
  const group = file.split('/')[0]!
  groups.set(group, [...groups.get(group) ?? [], file])
})
const entries = (list: string[], indent: string) =>
  list.map((file) => `${indent}'components/systems/${file}': ${name(files.indexOf(file))},`).join('\n')
const output = [
  '// Generated by scripts/system-sources.ts: the code view of each system example.',
  ...files.flatMap((file, index) => [
    '// @deno-types="./source-text.d.ts"',
    `import ${name(index)} from '../../../../../examples/systems/src/${file}?raw'`,
  ]),
  '',
  '/** Shared kit files, shown with every system example. */',
  'export const kitSources: Record<string, string> = {',
  entries(groups.get('kit') ?? [], '  '),
  '}',
  'export const systemSources: Record<string, Record<string, string>> = {',
  ...[...groups].filter(([group]) => group !== 'kit').flatMap(([group, list]) => [
    `  '${group}': {`,
    entries(list, '    '),
    '  },',
  ]),
  '}',
  '',
].join('\n')
Deno.writeTextFileSync(resolve(root, 'apps/docs/src/pages/studio/system-source-files.ts'), output)
